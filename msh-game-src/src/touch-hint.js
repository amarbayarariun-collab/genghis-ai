// Quest and hint lines keep keyboard names on a desktop.
// On a touch screen the same line names the control the player can see:
// Морь, Ярих, Нум, and the stick (жолоо).

const RULES = [
  [/WASD-аар алхаж,\s*←\s*→\s*сумаар эргэж,\s*хулганаа чирж харна/g, 'Жолоогоор алхаж, баруун талаар эргэ'],
  [/WASD(?:-аар)?/g, 'жолоо'],
  [/←\s*→\s*сумаар эргэж/g, 'баруун талаар эргэж'],
  [/мориор гатал \(F\)/gi, 'Морь дарж гатал'],
  [/Морио унаад \(F\)/g, 'Морь дарж'],
  [/морио унаад \(F\)/g, 'Морь дарж'],
  [/Морио унаж \(F\)/g, 'Морь дарж'],
  [/морио унаж \(F\)/g, 'Морь дарж'],
  [/Гүүгээ унаад \(F\)/g, 'Морь дарж'],
  [/Гүүгээ унаж \(F\)/g, 'Морь дарж'],
  [/Мориор \(F\)/g, 'Морь дарж'],
  [/мориор \(F\)/g, 'Морь дарж'],
  [/унаад \(F\)/g, 'Морь дарж'],
  [/унаж \(F\)/g, 'Морь дарж'],
  [/бууж \(F\)/g, 'Морь дарж бууж'],
  [/\[F\]\s*Морь унах/g, 'Морь'],
  [/\[F\]\s*/g, 'Морь · '],
  [/\(F\)/g, '· Морь'],
  [/F буух/g, 'Морь дарж бууна'],
  [/ярь \(E\)/g, 'Ярих'],
  [/шалга \(E\)/g, 'Ярих дарж шалга'],
  [/\[E\]\s*/g, 'Ярих · '],
  [/\(E\)/g, '· Ярих'],
  [/E дар/g, 'Ярих'],
  [/\[Q\]\s*|\(Q\)|Q дар(?![а-яөүёА-ЯӨҮЁ])/g, 'Нум'],
];

export function controlLine(text, touch) {
  if (text == null || !touch) return text;
  let s = String(text);
  for (const [re, to] of RULES) s = s.replace(re, to);
  return s.replace(/\s·\s*$/g, '').replace(/[ \t]{2,}/g, ' ');
}
